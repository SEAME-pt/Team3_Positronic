#!/usr/bin/env bash
# Export one sprint's GitHub milestone ("SPRINT NN") to Markdown: every issue,
# plus the pull requests that close them, with their Evidence and Safety impact.
# The file is a frozen record for the sprint review: rerun the script, don't edit it.
#
#   bash scripts/sprint_export.sh 1         writes docs/sprints/sprint_01_github.md
#   bash scripts/sprint_export.sh 1 -       prints to the terminal instead
#   GH_REPO=owner/name bash scripts/...     reads another repo than the git remote
#
# Runs on the host, not in the dev container: needs gh (logged in) and jq.
set -euo pipefail
cd "$(dirname "$0")/.."

usage() {
  echo "usage: $0 <sprint-number> [output-file|-]" >&2
  exit 2
}
[[ $# -ge 1 && $1 =~ ^[0-9]+$ ]] || usage
sprint=$(printf '%02d' "$((10#$1))")  # 10# so "08" isn't read as octal
milestone="SPRINT $sprint"
out=${2:-docs/sprints/sprint_${sprint}_github.md}

for tool in gh jq; do
  command -v "$tool" > /dev/null || { echo "missing: $tool (sudo apt install $tool)" >&2; exit 1; }
done
gh auth status > /dev/null 2>&1 || { echo "gh is not logged in: run gh auth login" >&2; exit 1; }

repo=${GH_REPO:-$(gh repo view --json nameWithOwner --jq .nameWithOwner)}

# A typo in the milestone title doesn't fail on GitHub's side: the lists come back
# empty. So check that it exists first, and show the real titles if it doesn't.
milestones=$(gh api "repos/$repo/milestones?state=all&per_page=100")
meta=$(jq --arg t "$milestone" '[.[] | select(.title == $t)] | first // empty' <<< "$milestones")
if [[ -z $meta ]]; then
  echo "no milestone \"$milestone\" in $repo. It has:" >&2
  jq -r '.[].title | "  " + .' <<< "$milestones" >&2
  exit 1
fi

issues=$(gh issue list -R "$repo" --milestone "$milestone" --state all --limit 500 \
  --json number,title,state,stateReason,assignees,labels,closedAt,url)

# PRs are rarely put in the milestone, so take them all and match them to the
# sprint's issues in jq below: by "Closes #n" in the body, or by our branch
# name convention "<issue#>-<slug>".
prs=$(gh pr list -R "$repo" --state all --limit 500 \
  --json number,title,state,mergedAt,url,author,headRefName,baseRefName,body)

markdown=$(jq -rn \
  --argjson meta "$meta" --argjson issues "$issues" --argjson prs "$prs" \
  --arg repo "$repo" --arg sprint "$sprint" --arg now "$(date -u '+%Y-%m-%d %H:%M UTC')" '
  def cell: tostring | gsub("\\|"; "\\|") | gsub("[\r\n]+"; " ");
  def day: if . then .[:10] else "" end;

  # Issue numbers this PR closes. GitHub closing keywords, case-insensitive.
  def refs:
    [(.body // "") | ascii_downcase
      | scan("(?:close[sd]?|fix(?:e[sd])?|resolve[sd]?):? +#([0-9]+)") | .[0] | tonumber]
    + [.headRefName // "" | capture("^(?<n>[0-9]+)-") | .n | tonumber];

  # Text of one "## <name>" section of our PR template, without its heading.
  # Bodies typed in the browser use \r\n, hence the gsub.
  def section($name; $placeholder):
    ((.body // "") | gsub("\r"; "") | "\n" + . | split("\n## ")
      | map(select(startswith($name))) | first // ""
      | sub("^[^\n]*\n?"; "") | sub("\\s+$"; "")) as $text
    | if $text == "" or $text == $placeholder then "_Not filled in._" else $text end;

  def status:
    if .state == "OPEN" then "open"
    elif .stateReason == "NOT_PLANNED" then "not planned"
    else "done" end;

  ($issues | map(.number)) as $ids
  | ($prs
      | map(. + {closes: (refs | unique | map(. as $n | select(any($ids[]; . == $n))))})
      | map(select(.closes | length > 0))
      | sort_by(.number)) as $linked
  | ($issues | sort_by(.number)) as $issues
  | ($issues | group_by(status) | map({key: (.[0] | status), value: length}) | from_entries) as $count

  | "# Sprint \($sprint): GitHub export",
    "",
    "Generated \($now) from `\($repo)`, milestone **\($meta.title)**"
      + " (\($meta.state)\(if $meta.due_on then ", due \($meta.due_on | day)" else "" end)).",
    "Generated by `scripts/sprint_export.sh \($sprint | tonumber)`: rerun it, don'\''t edit this file.",
    "",
    "**\($issues | length) issues:** \($count.done // 0) done, \($count."not planned" // 0) not planned,"
      + " \($count.open // 0) open.",
    "",
    "## Issues",
    "",
    "| # | Title | Status | Assignees | Labels | Closed | PRs |",
    "|---|---|---|---|---|---|---|",
    ($issues[] | . as $i
      | "| [#\(.number)](\(.url)) | \(.title | cell) | \(status) | "
        + "\([.assignees[].login | "@" + .] | join(", ")) | "
        + "\([.labels[].name] | join(", ") | cell) | \(.closedAt | day) | "
        + "\([$linked[] | select(any(.closes[]; . == $i.number)) | "#\(.number)"] | join(" ")) |"),
    "",
    "## Pull requests",
    "",
    if ($linked | length) == 0 then "_No pull request references these issues._" else
      ($linked[]
        | "### [#\(.number)](\(.url)) \(.title | cell)",
          "",
          (if .state == "MERGED" then "Merged \(.mergedAt | day)" else (.state | ascii_downcase) end)
            + " · @\(.author.login) · `\(.headRefName)` → `\(.baseRefName)`"
            + " · closes \([.closes[] | "#\(.)"] | join(" "))",
          "",
          "**Evidence**",
          "",
          section("Evidence"; "Measurements, plots, screenshots or logs that show it works."),
          "",
          "**Safety impact**",
          "",
          section("Safety impact";
            "none / motion / e-stop / limits / hardware. If not none, say what was checked."),
          "")
    end
')

if [[ $out == - ]]; then
  printf '%s\n' "$markdown"
else
  mkdir -p "$(dirname "$out")"
  printf '%s\n' "$markdown" > "$out"
  echo "wrote $out ($(jq length <<< "$issues") issues)"
fi
